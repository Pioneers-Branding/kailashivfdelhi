                        <h3>Embryo cryopreservation</h3>
                        <p>The embryologist evaluates any remaining embryos for cryopreservation (freezing). Embryo cryopreservation gives patients who wish to have another child the option to have an embryo transferred at a later date without having to complete another IVF cycle.</p>
                        <h3>After Transfer</h3>
                        <p>Two weeks after retrieval, a pregnancy blood test is performed. If this test is positive, the patient is considered four weeks pregnant.</p>
                        <h3>Understanding the Risks of IVF</h3>
                        <p>While IVF is generally safe, it’s important to understand potential risks:</p>
                        <ul class="unstyled-list">
                            <li><strong>Hormonal Side Effects:</strong> Some women experience mood swings or headaches due to hormone medications.</li>
                            <li><strong>Mild Discomfort:</strong> After egg collection, you might feel mild discomfort or spotting.</li>
                            <li><strong>Ovarian Hyperstimulation Syndrome (OHSS):</strong> Although rare, your ovaries may become over-stimulated, leading to discomfort.</li>
                        </ul>
                        <p>Important: Call Us Right Away If You Notice Any of These Symptoms:</p>
                        <ul class="unstyled-list-2">
                            <li>Difficulty passing urine</li>
                            <li>Severe belly pain or bloating</li>
                            <li>Rapid weight gain (within 3-5 days after egg retrieval)</li>
                        </ul>
